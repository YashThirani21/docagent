"""router: which pipeline each attachment goes to (Router called directly; nothing after it runs).

Dataset eval/datasets/router/cases.jsonl, generated by `python -m eval.build_router_set` (labels follow from how
each case was made), plus real photos in eval/datasets/router/real/ (split test).
Metrics: accuracy, confusion matrix, per tier (rule / vlm) accuracy and coverage, drawing->report_qa count
(the costly error: a drawing that gets a prose answer instead of its JSON), accuracy per way the case was made.
"""
from __future__ import annotations

import json
from pathlib import Path

from docagent.config import PROJECT_ROOT
from eval.core import mark, rate

NAME = "router"
ROOT = PROJECT_ROOT / "eval" / "datasets" / "router"
DATASET = [ROOT / "cases.jsonl"]
ROUTES = ("drawing", "report_qa")


def load_cases() -> list[dict]:
    cases = [json.loads(l) for l in (ROOT / "cases.jsonl").read_text().splitlines() if l.strip()]
    for f in sorted((ROOT / "real").glob("*")):          # user-added photos
        if f.suffix.lower() not in (".jpg", ".jpeg", ".png", ".webp", ".pdf"):
            continue
        side = f.with_suffix(f.suffix + ".json")
        expected = json.loads(side.read_text())["expected"] if side.exists() else f.name.split("__")[0]
        if expected in ROUTES:
            cases.append({"id": f"real-{f.stem}", "expected": expected, "made": "real photo", "split": "test",
                          "file": str(f.relative_to(PROJECT_ROOT))})
    return cases


def run_case(ctx, case: dict) -> dict:
    from docagent.schemas import Attachment, Request
    if case.get("file"):
        att = Attachment.from_path(PROJECT_ROOT / case["file"])
        req = Request(attachments=[att])
        with ctx.traced(req):
            d = ctx.agent.router.route_attachment(att)
    else:
        req = Request(text=case["text"])
        with ctx.traced(req):
            d = ctx.agent.router.route(req)[0]
    pred = d.route.value
    return {"id": case["id"], "request_id": req.request_id, "made": case["made"], "expected": case["expected"],
            "predicted": pred, "tier": d.tier, "confidence": round(d.confidence, 3), "reason": d.reason[:300],
            "pass": pred == case["expected"]}


def summarize(rows: list[dict]) -> dict:
    ok = [r for r in rows if "predicted" in r]
    conf = {e: {p: sum(1 for r in ok if r["expected"] == e and r["predicted"] == p) for p in ROUTES} for e in ROUTES}
    tiers = {}
    for t in ("rule", "vlm"):
        rs = [r for r in ok if r["tier"] == t]
        tiers[t] = {"n": len(rs), "coverage": round(len(rs) / len(ok), 3) if ok else None,
                    "accuracy": rate(r["pass"] for r in rs)}
    made = {}
    for r in ok:
        key = r["made"].split(",")[0]
        made.setdefault(key, []).append(r["pass"])
    return {
        "n": len(rows), "accuracy": rate(r.get("pass") for r in rows),
        "drawing_to_qa": conf["drawing"]["report_qa"], "qa_to_drawing": conf["report_qa"]["drawing"],
        "rule_coverage": tiers["rule"]["coverage"], "rule_accuracy": tiers["rule"]["accuracy"],
        "vlm_accuracy": tiers["vlm"]["accuracy"],
        "confusion": conf, "tiers": tiers, "by_source": {k: rate(v) for k, v in sorted(made.items())},
    }


def print_rows(rows: list[dict], args) -> None:
    print(f"\n{'id':28} {'expected':10} {'predicted':10} {'tier':5} {'conf':>5} ok  made")
    for r in rows:
        if args.verbose or not r.get("pass"):
            print(f"{r['id']:28} {r.get('expected', '?'):10} {r.get('predicted', '-'):10} {r.get('tier', '-'):5} "
                  f"{r.get('confidence', 0):5.2f} {mark(r.get('pass'))}   {r.get('made', '')} {r.get('error') or ''}")
    if not args.verbose:
        print(f"({sum(1 for r in rows if r.get('pass'))} correct cases not listed; --verbose lists all)")
